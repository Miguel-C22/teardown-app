import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import selfsigned from "selfsigned";

export interface TlsFiles {
  cert: string;
  key: string;
  source: "provided" | "self-signed";
}

function localNetworkAddresses(): string[] {
  return Object.values(os.networkInterfaces())
    .flat()
    .filter((networkInterface) => networkInterface && networkInterface.family === "IPv4" && !networkInterface.internal)
    .map((networkInterface) => networkInterface!.address);
}

// Prefers mkcert-style files in .certs/, otherwise creates and reuses a self-signed pair there.
export function loadTlsFiles(certificateDirectory: string): TlsFiles {
  const certPath = path.join(certificateDirectory, "cert.pem");
  const keyPath = path.join(certificateDirectory, "key.pem");
  const selfSignedMarker = path.join(certificateDirectory, ".self-signed");

  if (fs.existsSync(certPath) && fs.existsSync(keyPath)) {
    return {
      cert: fs.readFileSync(certPath, "utf8"),
      key: fs.readFileSync(keyPath, "utf8"),
      source: fs.existsSync(selfSignedMarker) ? "self-signed" : "provided",
    };
  }

  const alternativeNames = [
    { type: 2, value: "localhost" },
    { type: 7, ip: "127.0.0.1" },
    ...localNetworkAddresses().map((address) => ({ type: 7, ip: address })),
  ];
  const generated = selfsigned.generate([{ name: "commonName", value: "teardown-poc.local" }], {
    days: 365,
    keySize: 2048,
    algorithm: "sha256",
    extensions: [{ name: "subjectAltName", altNames: alternativeNames }],
  });

  fs.mkdirSync(certificateDirectory, { recursive: true });
  fs.writeFileSync(certPath, generated.cert);
  fs.writeFileSync(keyPath, generated.private);
  fs.writeFileSync(selfSignedMarker, "generated by server/src/certificates.ts\n");
  return { cert: generated.cert, key: generated.private, source: "self-signed" };
}

export { localNetworkAddresses };
